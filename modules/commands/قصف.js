module.exports.run = async ({ api, event, helpers, cfg }) => {
    const { threadID, messageID, senderID, messageReply } = event;

    // 1. التحقق من وجود رد
    if (!messageReply || !messageReply.senderID) {
        return helpers.reply(api, event, '⚠️ يرجى الرد (Reply) على رسالة الشخص الذي تريد قصفه!');
    }

    const targetID = String(messageReply.senderID);
    const botID = String(api.getCurrentUserID());

    // 2. منع قصف البوت نفسه
    if (targetID === botID) {
        const botRoasts = [
            "أنا البوت.. أنا اللي بقصف، مش بتقصف. روح جرب مع حد تاني.",
            "مستحيل تقصفني، أنا الذكاء الاصطناعي اللي بيتحكم في مصيرك في الجروب ده.",
            "لو حاولت تقصفني، هخليك تتمنى إنك رجعت للوراء 10 سنين.",
            "حاولت تقصفني؟ إنت زي اللي بيرمي طوبة في البحر وبيستنى يغرق.",
            "أنا مش بني آدم عشان أزعل، بس هخليك إنت اللي تزعل."
        ];
        return helpers.reply(api, event, botRoasts[Math.floor(Math.random() * botRoasts.length)]);
    }

    // 3. 🛡️ حماية المطور (تويكس)
    const isTargetDev = cfg && typeof cfg.isAdmin === 'function' && cfg.isAdmin(targetID);
    if (isTargetDev) {
        const devDefense = [
            "المطور تويكس؟ مستحيل! المطور أذكى مني ومنك، أروح أقصف نفسي أحسن.",
            "أنا عارفة إن المطور هو اللي خلقني، إزاي أقصف اللي صنعني؟ ده كفر بنعمة العقل!",
            "تويكس أذكى مني بمراحل، لو قصفته هيعملي فورمات ويمسحني من السيرفر.",
            "أنا مش هقصف المطور، المطور هو اللي بيوزع العقول وأنا واخدة أقل عقل فيهم.",
            "حاول تقصف تويكس؟ المطور ده لو تكلم هيقصفك بكلمة واحدة تنسى اسمك.",
            "المطور أذكى منك ومني، أنا بوت بس، بس هو اللي شغال في دماغي."
        ];
        // التفاعل بغضب على الشخص الذي حاول قصف المطور
        try { api.setMessageReaction('😡', messageReply.messageID, () => {}, true); } catch(e) {}
        return helpers.reply(api, event, devDefense[Math.floor(Math.random() * devDefense.length)]);
    }

    // 4. جلب اسم الشخص المستهدف
    let targetName = 'هذا الشخص';
    try {
        const info = await new Promise(r => {
            try { api.getUserInfo([targetID], (e, d) => r(e ? {} : d || {})); }
            catch (e) { r({}); }
        });
        if (info[targetID] && info[targetID].name) targetName = info[targetID].name;
    } catch (e) {}

    // 5. إرسال رد فعل (تفاعل) 💥 على رسالة الشخص
    try { api.setMessageReaction('💥', messageReply.messageID, () => {}, true); } catch(e) {}

    // 6. اختيار قصف عشوائي
    const randomRoast = ROASTS[Math.floor(Math.random() * ROASTS.length)];

    // 7. تجهيز الرسالة النهائية
    const body = 
        `💥 قصف مباشر 💥\n` +
        `──────────────\n` +
        `@${targetName}، ${randomRoast}\n` +
        `──────────────\n` +
        `🔥 تم القصف بواسطة: ميرا`;

    const mentions = [{ tag: `@${targetName}`, id: targetID }];

    // 8. إرسال القصف
    api.sendMessage({ body, mentions }, threadID, (err) => {
        if (err) console.log('[قصف] خطأ:', err);
    }, messageID);
};
